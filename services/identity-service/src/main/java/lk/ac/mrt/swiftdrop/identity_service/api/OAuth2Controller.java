package lk.ac.mrt.swiftdrop.identity_service.api;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.constraints.NotBlank;
import lk.ac.mrt.swiftdrop.identity_service.api.dto.GoogleAuthorizeResponse;
import lk.ac.mrt.swiftdrop.identity_service.config.GoogleOAuth2Properties;
import lk.ac.mrt.swiftdrop.identity_service.service.OAuth2StateService;
import org.springframework.http.MediaType;
import org.springframework.http.ProblemDetail;
import org.springframework.http.ResponseEntity;
import org.springframework.validation.annotation.Validated;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.util.UriComponentsBuilder;

import java.util.Objects;

/**
 * REST controller managing OAuth 2.0 / OIDC sign-in workflows 
 * Exposes endpoints for authorization URL generation and callback processing.
 */
@RestController
@RequestMapping(path = "/api/v1/auth/oauth2", produces = MediaType.APPLICATION_JSON_VALUE)
@Validated
@Tag(name = "OAuth2 Authentication", description = "Google OAuth 2.0 / OIDC authentication with PKCE")
public class OAuth2Controller {

    private final GoogleOAuth2Properties googleOAuth2Properties;
    private final OAuth2StateService oAuth2StateService;

    public OAuth2Controller(
            GoogleOAuth2Properties googleOAuth2Properties,
            OAuth2StateService oAuth2StateService
    ) {
        this.googleOAuth2Properties = Objects.requireNonNull(googleOAuth2Properties, "googleOAuth2Properties must not be null");
        this.oAuth2StateService = Objects.requireNonNull(oAuth2StateService, "oAuth2StateService must not be null");
    }

    @GetMapping(path = "/google/authorize")
    @Operation(
            summary = "Generate Google OAuth 2.0 authorization URL with PKCE",
            description = "Creates a cryptographically secure state token, binds it to the client's PKCE code challenge and redirect URI, and constructs the Google OAuth 2.0 authorization URL."
    )
    @ApiResponses(value = {
            @ApiResponse(
                    responseCode = "200",
                    description = "Successfully generated authorization URL and state",
                    content = @Content(mediaType = "application/json", schema = @Schema(implementation = GoogleAuthorizeResponse.class))
            ),
            @ApiResponse(
                    responseCode = "400",
                    description = "Missing or invalid codeChallenge parameter (RFC 7807)",
                    content = @Content(mediaType = "application/problem+json", schema = @Schema(implementation = ProblemDetail.class))
            )
    })
    public ResponseEntity<GoogleAuthorizeResponse> getGoogleAuthorizeUrl(
            @Parameter(description = "RFC 7636 S256 code challenge generated by the SPA client", required = true)
            @RequestParam(name = "codeChallenge")
            @NotBlank(message = "codeChallenge must not be blank")
            String codeChallenge,

            @Parameter(description = "Optional OAuth2 redirect URI (defaults to configured SPA callback URI)")
            @RequestParam(name = "redirectUri", required = false)
            String redirectUri
    ) {
        String effectiveRedirectUri = (redirectUri != null && !redirectUri.isBlank())
                ? redirectUri.trim()
                : googleOAuth2Properties.redirectUri();

        String state = oAuth2StateService.generateAndStoreState(codeChallenge.trim(), effectiveRedirectUri);

        String authorizationUrl = UriComponentsBuilder.fromUriString(googleOAuth2Properties.authorizationUri())
                .queryParam("response_type", "code")
                .queryParam("client_id", googleOAuth2Properties.clientId())
                .queryParam("redirect_uri", effectiveRedirectUri)
                .queryParam("scope", "openid email profile")
                .queryParam("state", state)
                .queryParam("code_challenge", codeChallenge.trim())
                .queryParam("code_challenge_method", "S256")
                .queryParam("prompt", "select_account")
                .build()
                .encode()
                .toUriString();

        return ResponseEntity.ok(new GoogleAuthorizeResponse(authorizationUrl, state));
    }
}
